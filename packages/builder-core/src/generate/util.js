// Small helpers shared by the generator files.
import { pascalCase } from '../model.js';

export const q = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
export const lit = v => (typeof v === 'string' ? q(v) : JSON.stringify(v));
export const iconComponent = name => `${pascalCase(name)}Icon`;
export const tsType = f => ({ number: 'number', boolean: 'boolean' }[f.type] || (f.type === 'enum' && f.options?.length ? f.options.map(q).join(' | ') : 'string'));
export const GEN_HEADER = '// Generated by Midas Code Builder — do not edit by hand; change the design/configuration and generate again.\n';

export function styleLit(style) {
    const entries = Object.entries(style || {}).filter(([, v]) => v !== undefined && v !== null && v !== '');
    return `{ ${entries.map(([k, v]) => `${k}: ${lit(v)}`).join(', ')} }`;
}

export const FLUID_COMPONENTS = new Set(['Table', 'FilterToolbar', 'SectionHeader', 'Card', 'StatCard', 'Alert']);

/**
 * Design widths in px (e.g. 1096px for a table) become fluid so pages stay responsive: inside a row → flex 1,
 * inside a column → stretch. Small elements (buttons, fields) keep their design size.
 */
export function fluid(style, parentStyle, always = false) {
    const px = parseFloat(style?.width);
    if (!style || !(px >= 480 || (always && px))) return style;
    const { width: _w, flexShrink: _f, ...rest } = style;
    return parentStyle?.flexDirection === 'row' ? { ...rest, flex: '1 1 0', minWidth: 0 } : { ...rest, alignSelf: 'stretch' };
}

/** Module folder relative to `src/modules` (nested modules follow their parents). */
export const moduleDir = (modules, m) => {
    const byId = new Map(modules.map(x => [x.id, x]));
    const parts = [];
    for (let c = m, n = 0; c && n < 20; c = c.parentId ? byId.get(c.parentId) : null, n++) parts.unshift(c.name);
    return parts.join('/');
};

/** Tailwind class for a label width in px (w-64 = 256px is the FormItem default). */
export const labelWidthClass = px => (Number(px) === 256 ? 'w-64' : `w-[${Number(px)}px]`);
