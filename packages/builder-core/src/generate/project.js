// "Download project": the base project template + the generated code + the library package, as one standalone project that
// installs with a plain `npm install` (the library is a local `file:` tarball, so no registry login is needed).
import { kebabCase } from '../screen.js';

/**
 * @param {Record<string,string>} template base-project files (text)
 * @param {Record<string,string>} generated output of generateProject()
 * @param {{ appName: string, libraryName: string, tarballName: string, tarball: Uint8Array }} opts
 */
export function assembleProject(template, generated, { appName, libraryName, tarballName, tarball }) {
    const files = { ...template, ...generated };
    delete files['.npmrc']; // the template's registry line needs a token env var; the vendored tarball does not
    const pkg = JSON.parse(files['package.json']);
    pkg.name = kebabCase(appName) || 'midas-app';
    pkg.version = '0.1.0';
    pkg.private = true;
    pkg.description = `${appName} — generated by Midas Code Builder`;
    // The library of the project replaces the template's default one (the app may use any @midas/ui-* package).
    pkg.dependencies = Object.fromEntries(Object.entries(pkg.dependencies || {}).filter(([n]) => n === libraryName || !/^@midas\/ui-/.test(n)));
    pkg.dependencies[libraryName] = `file:vendor/${tarballName}`;
    files['package.json'] = `${JSON.stringify(pkg, null, 2)}\n`;
    files[`vendor/${tarballName}`] = tarball;
    files['GETTING_STARTED.md'] = `# ${appName}\n\nGenerated by Midas Code Builder.\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n\nSign in with the mock account shown on the login page. Data is mocked (\`USE_MOCK\` in each module's \`api/mock.ts\`) until you connect your backend.\n\nThe UI library (${libraryName}) is bundled in \`vendor/\`; re-run \`midas generate\` or download the project again to update generated code.\n`;
    return files;
}
